//! Generatore dei moduli di dati di test srotolati: è l'equivalente
//! Rust di test.php, che in C genera test3.c / test3_function_*.c.
//!
//! Uso (dalla directory rust/):
//!
//!     cargo run --release --bin gen
//!
//! Produce:
//!
//!     src/test3.rs             (versione enum, TTC)
//!     src/dct_data.rs          (versione a puntatori di funzione, DCT)
//!     src/native_init_data.rs  (solo inizializzazione dello stack)
//!     src/native_call_data.rs  (init + chiamate srotolate)
//!
//! Il codice è volutamente srotolato (niente cicli) per restare
//! fedele ai file C generati: anche il costo di inizializzazione fa
//! parte del benchmark (vedi native_function_init).

use std::fmt::Write as _;
use std::fs;

const N: usize = 2000; // come $n in test.php

fn header() -> String {
    "// Code generated by `cargo run --bin gen` (equivalente di test.php). DO NOT EDIT.\n\n"
        .to_string()
}

/// stack[0]=2, stack[1..=N]=1, stack[N+1]=0, sp=N+2
fn stack_init(b: &mut String) {
    b.push_str("    v.pc = 0;\n");
    b.push_str("    v.sp = 0;\n");
    b.push_str("    v.stack[0] = 2.0;\n");
    for i in 1..=N {
        writeln!(b, "    v.stack[{i}] = 1.0;").unwrap();
    }
    writeln!(b, "    v.stack[{}] = 0.0;", N + 1).unwrap();
    writeln!(b, "    v.sp = {};", N + 2).unwrap();
}

/// code[N+1]=RETURN, code[N]=MUL, code[N-1..=0]=SUB (ordine decrescente, come test.php)
fn code_init(b: &mut String, ret: &str, mul: &str, sub: &str) {
    writeln!(b, "    v.code[{}] = {ret};", N + 1).unwrap();
    writeln!(b, "    v.code[{}] = {mul};", N).unwrap();
    for i in (0..N).rev() {
        writeln!(b, "    v.code[{i}] = {sub};").unwrap();
    }
    writeln!(b, "    v.code_size = {};", N + 2).unwrap();
}

fn main() {
    // --- versione TTC (enum), equivalente di test3.c ---
    let mut b = header();
    b.push_str("use crate::vm::{Opcode, VM};\n\n");
    b.push_str("/// Equivalente di `#include \"test3.c\"` nelle varianti TTC.\n");
    b.push_str("pub fn load_test3(v: &mut VM) {\n");
    stack_init(&mut b);
    code_init(
        &mut b,
        "Opcode::OP_RETURN",
        "Opcode::OP_MUL",
        "Opcode::OP_SUB",
    );
    b.push_str("}\n");
    fs::write("src/test3.rs", &b).unwrap();
    println!("scritto src/test3.rs");

    // --- versione DCT (puntatori di funzione) ---
    let mut b = header();
    b.push_str("use crate::dct::{self, Opcode, VM};\n\n");
    b.push_str("/// Equivalente di `#include \"test3.c\"` nella variante DCT:\n");
    b.push_str("/// il bytecode contiene direttamente i puntatori a funzione.\n");
    b.push_str("pub fn load_test3(v: &mut VM) {\n");
    stack_init(&mut b);
    code_init(
        &mut b,
        "dct::op_return as Opcode",
        "dct::op_mul as Opcode",
        "dct::op_sub as Opcode",
    );
    b.push_str("}\n");
    fs::write("src/dct_data.rs", &b).unwrap();
    println!("scritto src/dct_data.rs");

    // --- native_function_init: solo inizializzazione ---
    let mut b = header();
    b.push_str("use crate::vm::VM;\n\n");
    b.push_str("/// Equivalente di `#include \"test3_function_init.c\"`.\n");
    b.push_str("pub fn load_init(v: &mut VM) {\n");
    stack_init(&mut b);
    b.push_str("}\n");
    fs::write("src/native_init_data.rs", &b).unwrap();
    println!("scritto src/native_init_data.rs");

    // --- native_function_call: init + chiamate srotolate ---
    let mut b = header();
    b.push_str("use crate::native_call::*;\n");
    b.push_str("use crate::vm::VM;\n\n");
    b.push_str("/// Equivalente di `#include \"test3_function_call.c\"`.\n");
    b.push_str("pub fn load_and_call(v: &mut VM) {\n");
    stack_init(&mut b);
    for i in 0..N {
        // indice come commento in coda: rustfmt lo lascia sulla
        // stessa riga, così il file generato è fmt-stabile
        writeln!(b, "    F_OP_SUB(v); // {i}").unwrap();
    }
    writeln!(b, "    F_OP_MUL(v); // {}", N).unwrap();
    writeln!(b, "    F_OP_RETURN(v); // {}", N + 1).unwrap();
    b.push_str("}\n");
    fs::write("src/native_call_data.rs", &b).unwrap();
    println!("scritto src/native_call_data.rs");
}
