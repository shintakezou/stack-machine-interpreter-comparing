//! Porting Rust di transpiler.c
//!
//! Transpiler a passata singola da stack language a Rust: per ogni
//! token
//!   - numero     → emette una push sullo stack
//!   - primitiva  → emette la chiamata alla word corrispondente
//!
//! Le primitive disponibili sono i file rust/src/words/*.rs, mod.rs
//! escluso (come words/*.c per la versione C), caricati in ordine
//! alfabetico (read_dir non è deterministico come readdir(3), quindi
//! l'elenco viene ordinato esplicitamente).
//!
//! Come nel porting Go, non viene generato un equivalente di
//! transpiled_words_used.c: il codice non referenziato lo elimina il
//! linker; restano le statistiche di utilizzo.
//!
//! Uso (dalla directory rust/):
//!
//!     cargo run --release --bin transpiler -- [--words DIR] [--out FILE] <file.f>

use std::env;
use std::fs;
use std::process::exit;

fn main() {
    let mut words_dir = String::from("src/words");
    let mut out_file = String::from("src/transpiled.rs");
    let mut input: Option<String> = None;

    let mut args = env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--words" => words_dir = args.next().unwrap_or_else(|| usage()),
            "--out" => out_file = args.next().unwrap_or_else(|| usage()),
            _ => input = Some(arg),
        }
    }
    let input = input.unwrap_or_else(|| usage());

    // load_primitives: cerca le words definite in words/*.rs
    let mut words: Vec<String> = fs::read_dir(&words_dir)
        .unwrap_or_else(|e| {
            eprintln!("load primitives: {e}");
            exit(1);
        })
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            let name = e.file_name().into_string().ok()?;
            let stem = name.strip_suffix(".rs")?;
            if stem == "mod" {
                return None;
            }
            Some(stem.to_string())
        })
        .collect();
    words.sort();
    let mut used = vec![0usize; words.len()];

    let data = fs::read_to_string(&input).unwrap_or_else(|e| {
        eprintln!("{input}: {e}");
        exit(1);
    });
    if data.is_empty() {
        println!("File vuoto");
        return;
    }

    let mut out = String::from(
        "// Code generated by `cargo run --bin transpiler`. DO NOT EDIT.\n\n\
         use crate::vm::VM;\n\
         use crate::words;\n\n\
         /// Esegue il programma transpilato (equivalente di run() in\n\
         /// transpiled_main.c): nessun interprete, solo chiamate native.\n\
         pub fn run() {\n\
         \x20   let mut m = VM::new();\n\
         \x20   let v = &mut m;\n\
         \x20   v.pc = 0;\n\
         \x20   v.sp = 0;\n",
    );

    // passata singola sui token
    let mut risultato = 0;
    for tok in data.split_whitespace() {
        if let Ok(num) = tok.parse::<f64>() {
            out.push_str(&format!("    v.push({num:.6});\n"));
            continue;
        }
        if let Some(i) = words.iter().position(|w| w == tok) {
            used[i] += 1;
            out.push_str(&format!("    words::{tok}(v);\n"));
            continue;
        }
        eprintln!("token sconosciuto: {tok:?}");
        risultato = 1;
        break;
    }

    out.push_str("}\n");
    fs::write(&out_file, &out).unwrap_or_else(|e| {
        eprintln!("{out_file}: {e}");
        exit(1);
    });

    // some stats: primitive used
    println!("\n\nPRIMITIVE STATS:");
    for (i, w) in words.iter().enumerate() {
        println!("used:{} word:{}", used[i], w);
    }

    exit(risultato);
}

fn usage() -> ! {
    eprintln!("Uso: transpiler [--words dir] [--out file] <file>");
    exit(1);
}
