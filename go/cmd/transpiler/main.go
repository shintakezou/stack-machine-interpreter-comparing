// Porting Go di transpiler.c
//
// Transpiler a passata singola da stack language a Go: per ogni token
//   - numero     → emette una Push sullo stack
//   - primitiva  → emette la chiamata alla word corrispondente
//
// Le primitive disponibili sono i file go/words/*.go (come words/*.c
// per la versione C), caricati in ordine alfabetico (os.ReadDir è già
// deterministico, al contrario di readdir(3)).
//
// Differenza rispetto al C: non viene generato un equivalente di
// transpiled_words_used.c, perché il linker Go elimina da sé il
// codice non referenziato; restano le statistiche di utilizzo.
//
// Uso (dalla root del repo):
//
//	build/go/transpiler [-words go/words] [-out go/transpiled/transpiled_main.go] <file.f>
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"
)

var (
	wordsDir = flag.String("words", "go/words", "directory delle primitive (words)")
	outFile  = flag.String("out", "go/transpiled/transpiled_main.go", "file Go generato")
)

// exported converte il nome di una word nel nome Go esportato
// (nop → Nop; le word maiuscole restano invariate).
func exported(name string) string {
	r := []rune(name)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// load_primitives: cerca le words definite in words/*.go
func loadPrimitives(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var words []string
	for _, e := range entries {
		name := e.Name()
		if strings.HasSuffix(name, ".go") {
			words = append(words, strings.TrimSuffix(name, ".go"))
		}
	}
	return words, nil
}

func main() {
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintf(os.Stderr, "Uso: %s [-words dir] [-out file] <file>\n", os.Args[0])
		os.Exit(1)
	}

	words, err := loadPrimitives(*wordsDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "load primitives:", err)
		os.Exit(1)
	}
	index := make(map[string]int, len(words))
	for i, w := range words {
		index[w] = i
	}
	used := make([]int, len(words))

	data, err := os.ReadFile(flag.Arg(0))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if len(data) == 0 {
		fmt.Println("File vuoto")
		return
	}

	var b strings.Builder

	// generate transpiled: HEADER
	b.WriteString(`// Code generated by cmd/transpiler. DO NOT EDIT.
package transpiled

import (
	"stackmachine/vm"
	"stackmachine/words"
)

// Run esegue il programma transpilato (equivalente di run() in
// transpiled_main.c): nessun interprete, solo chiamate native.
func Run() {
	var m vm.VM
	v := &m
	v.PC = 0
	v.SP = 0
`)

	// generate transpiled: BODY (passata singola sui token)
	risultato := 0
	for _, tok := range strings.Fields(string(data)) {
		if num, err := strconv.ParseFloat(tok, 64); err == nil {
			fmt.Fprintf(&b, "\tv.Push(%f)\n", num)
			continue
		}
		if i, ok := index[tok]; ok {
			used[i]++
			fmt.Fprintf(&b, "\twords.%s(v)\n", exported(tok))
			continue
		}
		fmt.Fprintf(os.Stderr, "token sconosciuto: %q\n", tok)
		risultato = 1
		break
	}

	// generate transpiled: FOOTER
	b.WriteString("}\n")

	if err := os.MkdirAll(filepath.Dir(*outFile), 0755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outFile, []byte(b.String()), 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	// some stats: primitive used
	fmt.Printf("\n\nPRIMITIVE STATS:\n")
	for i, w := range words {
		fmt.Printf("used:%d ", used[i])
		fmt.Printf("word:%s\n", w)
	}

	os.Exit(risultato)
}
