// Generatore dei file di dati di test srotolati: è l'equivalente Go di
// test.php, che in C genera test3.c / test3_function_*.c.
//
// Uso (dalla directory go/):
//
//	go run ./gen
//
// Produce:
//
//	vm/test3_data.go                                (versione enum, TTC)
//	cmd/i_DCT_dispatch_function_call/test3_data.go  (versione a puntatori di funzione, DCT)
//	cmd/native_function_init/test3_init_data.go     (solo inizializzazione dello stack)
//	cmd/native_function_call/test3_call_data.go     (init + chiamate srotolate)
//
// Il codice è volutamente srotolato (niente cicli) per restare fedele
// ai file C generati: anche il costo di inizializzazione fa parte del
// benchmark (vedi native_function_init).
package main

import (
	"fmt"
	"log"
	"os"
	"strings"
)

const n = 2000 // come $n in test.php

func header(pkg string) string {
	return "// Code generated by go run ./gen (equivalente di test.php). DO NOT EDIT.\n\npackage " + pkg + "\n"
}

// stackInit emette l'inizializzazione dello stack comune a tutte le
// varianti: stack[0]=2, stack[1..n]=1, stack[n+1]=0, sp=n+2.
func stackInit(b *strings.Builder, recv string) {
	fmt.Fprintf(b, "\t%s.PC = 0\n", recv)
	fmt.Fprintf(b, "\t%s.SP = 0\n", recv)
	fmt.Fprintf(b, "\t%s.Stack[0] = +2\n", recv)
	for i := 1; i <= n; i++ {
		fmt.Fprintf(b, "\t%s.Stack[%d] = +1\n", recv, i)
	}
	fmt.Fprintf(b, "\t%s.Stack[%d] = 0\n", recv, n+1)
	fmt.Fprintf(b, "\t%s.SP = %d\n", recv, n+2)
}

// codeInit emette il riempimento di code[]: RETURN, MUL, poi n SUB
// (in ordine decrescente di indice, come test.php).
func codeInit(b *strings.Builder, recv, opRet, opMul, opSub string) {
	fmt.Fprintf(b, "\t%s.Code[%d] = %s\n", recv, n+1, opRet)
	fmt.Fprintf(b, "\t%s.Code[%d] = %s\n", recv, n, opMul)
	for i := n - 1; i >= 0; i-- {
		fmt.Fprintf(b, "\t%s.Code[%d] = %s\n", recv, i, opSub)
	}
	fmt.Fprintf(b, "\t%s.CodeSize = %d\n", recv, n+2)
}

func write(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("scritto", path)
}

func main() {
	// --- versione TTC (enum), equivalente di test3.c ---
	var b strings.Builder
	b.WriteString(header("vm"))
	b.WriteString("\n// LoadTest3 è l'equivalente di #include \"test3.c\" nelle varianti TTC.\nfunc LoadTest3(v *VM) {\n")
	stackInit(&b, "v")
	codeInit(&b, "v", "OP_RETURN", "OP_MUL", "OP_SUB")
	b.WriteString("}\n")
	write("vm/test3_data.go", b.String())

	// --- versione DCT (puntatori di funzione) ---
	b.Reset()
	b.WriteString(header("main"))
	b.WriteString("\n// loadTest3 è l'equivalente di #include \"test3.c\" nella variante DCT:\n// il bytecode contiene direttamente i valori funzione.\nfunc loadTest3(v *VM) {\n")
	stackInit(&b, "v")
	codeInit(&b, "v", "opRETURN", "opMUL", "opSUB")
	b.WriteString("}\n")
	write("cmd/i_DCT_dispatch_function_call/test3_data.go", b.String())

	// --- native_function_init: solo inizializzazione (test3_function_init.c) ---
	b.Reset()
	b.WriteString(header("main"))
	b.WriteString("\nimport \"stackmachine/vm\"\n")
	b.WriteString("\n// loadInit è l'equivalente di #include \"test3_function_init.c\".\nfunc loadInit(v *vm.VM) {\n")
	stackInit(&b, "v")
	b.WriteString("}\n")
	write("cmd/native_function_init/test3_init_data.go", b.String())

	// --- native_function_call: init + chiamate srotolate (test3_function_call.c) ---
	b.Reset()
	b.WriteString(header("main"))
	b.WriteString("\nimport \"stackmachine/vm\"\n")
	b.WriteString("\n// loadAndCall è l'equivalente di #include \"test3_function_call.c\".\nfunc loadAndCall(v *vm.VM) {\n")
	stackInit(&b, "v")
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "\t/*%4d*/ F_OP_SUB(v)\n", i)
	}
	fmt.Fprintf(&b, "\t/*%4d*/ F_OP_MUL(v)\n", n)
	fmt.Fprintf(&b, "\t/*%4d*/ F_OP_RETURN(v)\n", n+1)
	b.WriteString("}\n")
	write("cmd/native_function_call/test3_call_data.go", b.String())
}
